module Show_lock = struct
  let print_lock lock_dir_arg () =
    let open Fiber.O in
    let* workspace = Memo.run (Workspace.workspace ()) in
    let source_paths =
      Pkg.Pkg_common.Lock_dirs_arg.lock_dirs_of_workspace lock_dir_arg workspace
    in
    let exists path = Fpath.exists (Path.to_string path) in
    (* Lock dirs that are already committed are read directly from disk. Those
       without a committed lock dir are autolocked via the build system. *)
    let uncommitted_lock_dirs =
      List.filter source_paths ~f:(fun source_path ->
        not (exists (Path.source source_path)))
    in
    let* () =
      (* Only build when package management is active for these lock dirs. *)
      match uncommitted_lock_dirs with
      | [] -> Fiber.return ()
      | _ :: _
        when not
               (Pkg.Pkg_common.pkg_enabled
                  ~workspace
                  ~lock_dir_paths:uncommitted_lock_dirs) -> Fiber.return ()
      | _ :: _ ->
        Build.build_memo_exn (fun () ->
          Memo.parallel_iter uncommitted_lock_dirs ~f:(fun source_path ->
            Build_system.build_dir (Dune_rules.Lock_dir.lock_dir_of_source source_path)))
    in
    Fiber.parallel_map source_paths ~f:(fun source_path ->
      let lock_dir_path = Path.source source_path in
      let+ platform = Pkg.Pkg_common.solver_env_from_system_and_context ~lock_dir_path in
      let read_path =
        if exists lock_dir_path
        then Some lock_dir_path
        else (
          let internal = Dune_rules.Lock_dir.lock_dir_of_source source_path in
          Option.some_if (exists internal) internal)
      in
      match read_path with
      | None ->
        Pp.textf
          "No lock directory found for %s (none committed and none generated by a build \
           yet)."
          (Path.to_string_maybe_quoted lock_dir_path)
      | Some read_path ->
        let lock_dir = Lock_dir.read_disk_exn read_path in
        let packages =
          Lock_dir.Packages.pkgs_on_platform_by_name lock_dir.packages ~platform
          |> Package_name.Map.values
        in
        Pp.concat
          ~sep:Pp.space
          [ Pp.hovbox
            @@ Pp.textf "Contents of %s:" (Path.to_string_maybe_quoted read_path)
          ; Pkg.Pkg_common.pp_packages packages
          ]
        |> Pp.vbox)
    >>| Console.print
  ;;

  let term =
    let+ builder = Common.Builder.term
    and+ lock_dir_arg = Pkg.Pkg_common.Lock_dirs_arg.term in
    let common, config = Common.init builder in
    Scheduler_setup.go_with_rpc_server ~common ~config @@ print_lock lock_dir_arg
  ;;

  let command =
    let doc = "Display packages in a lock file" in
    let info = Cmd.info ~doc "lock" in
    Cmd.v info term
  ;;
end

module Dependency_hash = struct
  let print_local_packages_hash () =
    let open Fiber.O in
    let+ local_packages =
      Pkg.Pkg_common.find_local_packages
      |> Memo.run
      >>| Package_name.Map.values
      >>| List.map ~f:Local_package.for_solver
    in
    let hash =
      Local_package.For_solver.non_local_dependencies local_packages
      |> Local_package.Dependency_hash.of_dependency_formula
    in
    match hash with
    | None -> User_error.raise [ Pp.text "No non-local dependencies" ]
    | Some dependency_hash ->
      print_endline (Local_package.Dependency_hash.to_string dependency_hash)
  ;;

  let term =
    let+ builder = Common.Builder.term in
    let builder = Common.Builder.forbid_builds builder in
    let common, config = Common.init builder in
    Scheduler_setup.go_with_rpc_server ~common ~config print_local_packages_hash
  ;;

  let info =
    let doc =
      "Print the hash of the project's non-local dependencies such as what would appear \
       in the \"dependency_hash\" field of a a lock.dune file."
    in
    Cmd.info "dependency-hash" ~doc
  ;;

  let command = Cmd.v info term
end

module List_locked_dependencies = struct
  module Package_universe = Dune_pkg.Package_universe
  module Lock_dir = Dune_pkg.Lock_dir
  module Opam_repo = Dune_pkg.Opam_repo
  module Package_version = Dune_pkg.Package_version
  module Opam_solver = Dune_pkg.Opam_solver

  let info =
    let doc = "List the dependencies locked by a lockdir" in
    let man = [ `S "DESCRIPTION"; `P "List the dependencies locked by a lockdir" ] in
    Cmd.info "list-locked-dependencies" ~doc ~man
  ;;

  let package_deps_in_lock_dir_pp package_universe package_name ~transitive =
    let traverse, traverse_word =
      if transitive then `Transitive, "Transitive" else `Immediate, "Immediate"
    in
    let opam_package =
      Package_universe.opam_package_of_package package_universe package_name
    in
    let list_dependencies which =
      Package_universe.opam_package_dependencies_of_package
        package_universe
        package_name
        ~which
        ~traverse
    in
    Pp.concat
      ~sep:Pp.cut
      [ Pp.hbox
          (Pp.textf
             "%s dependencies of local package %s"
             traverse_word
             (OpamPackage.to_string opam_package))
      ; Pp.enumerate (list_dependencies `Non_test) ~f:(fun opam_package ->
          Pp.text (OpamPackage.to_string opam_package))
      ; Pp.enumerate (list_dependencies `Test_only) ~f:(fun opam_package ->
          Pp.textf "%s (test only)" (OpamPackage.to_string opam_package))
      ]
    |> Pp.vbox
  ;;

  let enumerate_lock_dirs_by_path workspace ~lock_dirs =
    let lock_dirs =
      Pkg.Pkg_common.Lock_dirs_arg.lock_dirs_of_workspace lock_dirs workspace
    in
    List.filter_map lock_dirs ~f:(fun lock_dir_path ->
      if Fpath.exists (Path.Source.to_string lock_dir_path)
      then (
        match Lock_dir.read_disk_exn (Path.source lock_dir_path) with
        | lock_dir -> Some (lock_dir_path, lock_dir)
        | exception User_error.E e ->
          User_warning.emit
            [ Pp.textf
                "Failed to parse lockdir %s:"
                (Path.Source.to_string_maybe_quoted lock_dir_path)
            ; User_message.pp e
            ];
          None)
      else None)
  ;;

  let list_locked_dependencies ~transitive ~lock_dirs () =
    let open Fiber.O in
    let* lock_dirs_by_path, local_packages =
      let open Memo.O in
      Memo.both
        (Workspace.workspace () >>| enumerate_lock_dirs_by_path ~lock_dirs)
        Pkg.Pkg_common.find_local_packages
      |> Memo.run
    in
    let+ pp =
      Fiber.parallel_map lock_dirs_by_path ~f:(fun (lock_dir_path, lock_dir) ->
        let lock_dir_path = Path.source lock_dir_path in
        let+ platform =
          Pkg.Pkg_common.solver_env_from_system_and_context ~lock_dir_path
        in
        let package_universe =
          Package_universe.create ~platform local_packages lock_dir |> User_error.ok_exn
        in
        Pp.vbox
          (Pp.concat
             ~sep:Pp.cut
             [ Pp.hbox
                 (Pp.textf
                    "Dependencies of local packages locked in %s"
                    (Path.to_string_maybe_quoted lock_dir_path))
             ; Pp.enumerate
                 (Package_name.Map.keys local_packages)
                 ~f:(package_deps_in_lock_dir_pp package_universe ~transitive)
               |> Pp.box
             ]))
      >>| Pp.concat ~sep:Pp.cut
      >>| Pp.vbox
    in
    Console.print [ pp ]
  ;;

  let term =
    let+ builder = Common.Builder.term
    and+ transitive =
      Arg.(
        value
        & flag
        & info
            [ "transitive" ]
            ~doc:
              (Some
                 "Display transitive dependencies (by default only immediate \
                  dependencies are displayed)"))
    and+ lock_dirs = Pkg.Pkg_common.Lock_dirs_arg.term in
    let builder = Common.Builder.forbid_builds builder in
    let common, config = Common.init builder in
    Scheduler_setup.go_with_rpc_server ~common ~config
    @@ list_locked_dependencies ~transitive ~lock_dirs
  ;;

  let command = Cmd.v info term
end

(* The dependency tree of the local packages locked in a lockdir. Each package's
   subtree is expanded only the first time it is encountered; [occurrences]
   records how many times a package occurs in the fully-expanded tree. *)
module Dependency_tree = struct
  module Package_universe = Dune_pkg.Package_universe

  type t =
    { package : OpamPackage.t
    ; occurrences : int
    ; deps : t list
    }

  (* Immediate dependencies of [package_name] on [platform]. Local packages
     aren't present in the lockdir, so their dependencies are resolved through
     the package universe; the dependencies of all other (locked) packages are
     read directly from the lockdir's dependency graph. *)
  let immediate_dependencies
        package_universe
        ~local_packages
        ~platform_pkgs
        ~platform
        package_name
    =
    let deps =
      if Package_name.Map.mem local_packages package_name
      then
        Package_universe.opam_package_dependencies_of_package
          package_universe
          package_name
          ~which:`All
          ~traverse:`Immediate
        |> List.map ~f:(fun opam_package ->
          Dune_pkg.Package_name.of_opam_package_name (OpamPackage.name opam_package))
      else (
        match Package_name.Map.find platform_pkgs package_name with
        | None -> []
        | Some (pkg : Lock_dir.Pkg.t) ->
          Lock_dir.Conditional_choice.choose_for_platform pkg.depends ~platform
          |> Option.value ~default:[]
          |> List.filter_map ~f:(fun (dep : Lock_dir.Dependency.t) ->
            Option.some_if (Package_name.Map.mem platform_pkgs dep.name) dep.name))
    in
    List.sort deps ~compare:Package_name.compare
  ;;

  let create package_universe ~local_packages ~platform_pkgs ~platform roots =
    (* Memoized so that the parents-graph and tree-building traversals don't each
       re-resolve a package's dependencies (formula resolution for local
       packages is not free). *)
    let immediate_dependencies =
      let immediate_deps = ref Package_name.Map.empty in
      fun package_name ->
        match Package_name.Map.find !immediate_deps package_name with
        | Some deps -> deps
        | None ->
          let deps =
            immediate_dependencies
              package_universe
              ~local_packages
              ~platform_pkgs
              ~platform
              package_name
          in
          immediate_deps := Package_name.Map.set !immediate_deps package_name deps;
          deps
    in
    (* Reverse dependency graph: the parents of each reachable package. Each
       package's dependencies are expanded only once, so every edge is recorded
       exactly once. *)
    let parents =
      let rec collect (parents, seen) package_name =
        if Package_name.Set.mem seen package_name
        then parents, seen
        else (
          let seen = Package_name.Set.add seen package_name in
          List.fold_left
            (immediate_dependencies package_name)
            ~init:(parents, seen)
            ~f:(fun (parents, seen) dependency ->
              let parents = Package_name.Map.add_multi parents dependency package_name in
              collect (parents, seen) dependency))
      in
      List.fold_left
        roots
        ~init:(Package_name.Map.empty, Package_name.Set.empty)
        ~f:collect
      |> fst
    in
    (* The number of times a package occurs in the fully-expanded tree: once for
       each local package that is a root, plus, for each package that depends on
       it, that package's own number of occurrences. *)
    let occurrences =
      let cache = ref Package_name.Map.empty in
      let rec occurrences package_name =
        match Package_name.Map.find !cache package_name with
        | Some n -> n
        | None ->
          let from_roots =
            if Package_name.Map.mem local_packages package_name then 1 else 0
          in
          let n =
            Package_name.Map.find parents package_name
            |> Option.value ~default:[]
            |> List.fold_left ~init:from_roots ~f:(fun acc parent ->
              acc + occurrences parent)
          in
          cache := Package_name.Map.set !cache package_name n;
          n
      in
      occurrences
    in
    (* A package's subtree is expanded the first time it is encountered; later
       encounters become leaves. [visited] is threaded through the traversal in
       depth-first order rather than kept in a mutable cell. *)
    let rec node visited package_name =
      let make deps =
        { package = Package_universe.opam_package_of_package package_universe package_name
        ; occurrences = occurrences package_name
        ; deps
        }
      in
      if Package_name.Set.mem visited package_name
      then visited, make []
      else (
        let visited = Package_name.Set.add visited package_name in
        let visited, deps =
          List.fold_map (immediate_dependencies package_name) ~init:visited ~f:node
        in
        visited, make deps)
    in
    List.fold_map roots ~init:Package_name.Set.empty ~f:node |> snd
  ;;

  let pp forest =
    let rec pp_node { package; occurrences; deps } =
      let label =
        let name = OpamPackage.to_string package in
        if occurrences > 1 then sprintf "%s (*%d)" name occurrences else name
      in
      match deps with
      | [] -> Pp.text label
      | _ :: _ ->
        Pp.vbox
          (Pp.concat
             ~sep:Pp.cut
             [ Pp.hbox (Pp.text label); Pp.enumerate deps ~f:pp_node |> Pp.box ])
    in
    Pp.enumerate forest ~f:pp_node |> Pp.box
  ;;
end

module Tree = struct
  module Package_universe = Dune_pkg.Package_universe

  let info =
    let doc = "Display the dependency tree of the packages in a lockdir" in
    let man = [ `S "DESCRIPTION"; `P doc ] in
    Cmd.info "tree" ~doc ~man
  ;;

  let print_tree ~lock_dirs () =
    let open Fiber.O in
    let* lock_dirs_by_path, local_packages =
      let open Memo.O in
      Memo.both
        (Workspace.workspace ()
         >>| List_locked_dependencies.enumerate_lock_dirs_by_path ~lock_dirs)
        Pkg.Pkg_common.find_local_packages
      |> Memo.run
    in
    let+ pp =
      Fiber.parallel_map lock_dirs_by_path ~f:(fun (lock_dir_path, lock_dir) ->
        let lock_dir_path = Path.source lock_dir_path in
        let+ platform =
          Pkg.Pkg_common.solver_env_from_system_and_context ~lock_dir_path
        in
        let package_universe =
          Package_universe.create ~platform local_packages lock_dir |> User_error.ok_exn
        in
        let platform_pkgs =
          Lock_dir.Packages.pkgs_on_platform_by_name lock_dir.packages ~platform
        in
        Pp.vbox
          (Pp.concat
             ~sep:Pp.cut
             [ Pp.hbox
                 (Pp.textf
                    "Dependency tree of local packages locked in %s"
                    (Path.to_string_maybe_quoted lock_dir_path))
             ; Dependency_tree.create
                 package_universe
                 ~local_packages
                 ~platform_pkgs
                 ~platform
                 (Package_name.Map.keys local_packages)
               |> Dependency_tree.pp
             ]))
      >>| Pp.concat ~sep:Pp.cut
      >>| Pp.vbox
    in
    Console.print [ pp ]
  ;;

  let term =
    let+ builder = Common.Builder.term
    and+ lock_dirs = Pkg.Pkg_common.Lock_dirs_arg.term in
    let builder = Common.Builder.forbid_builds builder in
    let common, config = Common.init builder in
    Scheduler_setup.go_with_rpc_server ~common ~config @@ print_tree ~lock_dirs
  ;;

  let command = Cmd.v info term
end

let command =
  let doc = "Subcommands related to package management" in
  let info = Cmd.info ~doc "pkg" in
  Cmd.group
    info
    [ Show_lock.command
    ; List_locked_dependencies.command
    ; Tree.command
    ; Dependency_hash.command
    ]
;;
